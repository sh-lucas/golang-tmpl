// Command schema prints the database schema produced by all migrations (just check writes it to database/schema.sql).
package main

import (
	"context"
	"database/sql"
	"fmt"
	"os"

	"github.com/rox-projects/golang-tmpl/database/migrations"
	_ "modernc.org/sqlite"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "schema:", err)
		os.Exit(1)
	}
}

func run() error {
	ctx := context.Background()
	db, err := sql.Open("sqlite", ":memory:")
	if err != nil {
		return err
	}
	defer db.Close()
	// Each :memory: connection is a separate database.
	db.SetMaxOpenConns(1)
	if err := migrations.Run(ctx, db); err != nil {
		return err
	}
	// Grouped by table, so a migration's position in history does not reorder the file.
	rows, err := db.QueryContext(ctx, `SELECT sql FROM sqlite_schema
		WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
		ORDER BY tbl_name, type <> 'table', name`)
	if err != nil {
		return err
	}
	defer rows.Close()
	fmt.Println("-- Generated by `go run ./cmd/schema` from database/migrations; do not edit.")
	for rows.Next() {
		var statement string
		if err := rows.Scan(&statement); err != nil {
			return err
		}
		fmt.Printf("\n%s;\n", statement)
	}
	return rows.Err()
}
